interface AIProviderIconProps {
  provider: SupportedProvider | string;
  size?: "sm" | "md" | "lg";
  className?: string;
}

export function AIProviderIcon({
  provider,
  size = "md",
  className,
}: AIProviderIconProps) {
  const sizeClasses = {
    sm: "h-6 w-6 rounded-md p-1",
    md: "h-7 w-7 rounded-lg p-1.5",
    lg: "h-8 w-8 rounded-lg p-1.5",
  };

  const iconSizes = {
    sm: "h-3.5 w-3.5",
    md: "h-4 w-4",
    lg: "h-5 w-5",
  };

  const containerClasses: Record<string, string> = {
    google: "bg-blue-50/70 border border-blue-200/60 text-blue-600",
    openai: "bg-emerald-50/70 border border-emerald-200/60 text-emerald-600",
    anthropic: "bg-orange-50/70 border border-orange-200/60 text-orange-600",
    groq: "bg-red-50/70 border border-red-200/60 text-red-600",
    deepseek: "bg-indigo-50/70 border border-indigo-200/60 text-indigo-600",
    "9router-public": "bg-amber-50/70 border border-amber-200/60 text-amber-700",
  };

  const container =
    containerClasses[provider] || "bg-slate-50 border border-slate-200 text-slate-700";
  const iconCls = iconSizes[size];

  const renderIcon = () => {
    switch (provider) {
      case "google":
        return <GeminiIcon className={iconCls} />;
      case "openai":
        return <OpenAIIcon className={iconCls} />;
      case "anthropic":
        return <ClaudeIcon className={iconCls} />;
      case "groq":
        return <GroqIcon className={iconCls} />;
      case "deepseek":
        return <DeepSeekIcon className={iconCls} />;
      case "9router-public":
        return <NineRouterIcon className={iconCls} />;
      default:
        return (
          <span className="font-bold text-[10px] uppercase">
            {provider.slice(0, 2)}
          </span>
        );
    }
  };

  return (
    <span
      className={cn(
        "inline-flex shrink-0 items-center justify-center transition-transform",
        sizeClasses[size],
        container,
        className,
      )}
      aria-label={provider}
    >
      {renderIcon()}
    </span>
  );
}
